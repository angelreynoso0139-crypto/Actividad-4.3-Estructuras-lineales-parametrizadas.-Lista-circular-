private void configurarEventos() {
        cmbTipo.addActionListener(e -> actualizarCamposPorTipo());

        btnInsertarInicio.addActionListener(e -> {
            Proyeccion p = crearFuncionDesdeFormulario();
            if (p != null) {
                listaFunciones.insertarInicio(p);
                limpiarCampos();
                actualizarVista();
            }
        });

        btnInsertarFinal.addActionListener(e -> {
            Proyeccion p = crearFuncionDesdeFormulario();
            if (p != null) {
                listaFunciones.insertarFinal(p);
                limpiarCampos();
                actualizarVista();
            }
        });

        btnInsertarPos.addActionListener(e -> {
            Proyeccion p = crearFuncionDesdeFormulario();
            if (p != null) {
                try {
                    int pos = Integer.parseInt(txtPosicion.getText().trim());
                    listaFunciones.insertarPosicion(p, pos);
                    limpiarCampos();
                    actualizarVista();
                } catch (NumberFormatException ex) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Ingresa una posición numérica válida.");
                } catch (IndexOutOfBoundsException ex) {
                    javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage());
                }
            }
        });

        btnEliminarPos.addActionListener(e -> {
            try {
                int pos = Integer.parseInt(txtPosicion.getText().trim());
                Proyeccion eliminada = listaFunciones.eliminar(pos);
                javax.swing.JOptionPane.showMessageDialog(this, "Eliminada: " + eliminada.getTitulo());
                txtPosicion.setText("");
                actualizarVista();
            } catch (NumberFormatException ex) {
                javax.swing.JOptionPane.showMessageDialog(this, "Ingresa una posición numérica válida.");
            } catch (Exception ex) {
                javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage());
            }
        });

        btnEliminarTitulo.addActionListener(e -> {
            String titulo = txtTitulo.getText().trim();
            if (titulo.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Escribe el título de la película a eliminar.");
                return;
            }
            try {
                Proyeccion eliminada = listaFunciones.eliminarPorTitulo(titulo);
                if (eliminada != null) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Función eliminada: " + eliminada.getTitulo());
                    txtTitulo.setText("");
                    actualizarVista();
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "No se encontró ninguna función con ese título.");
                }
            } catch (Exception ex) {
                javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage());
            }
        });

        btnAnterior.addActionListener(e -> {
            listaFunciones.anterior();
            actualizarVista();
        });

        btnSiguiente.addActionListener(e -> {
            listaFunciones.siguiente();
            actualizarVista();
        });

        btnMostrarTodos.addActionListener(e -> actualizarVista());

        btnVaciar.addActionListener(e -> {
            listaFunciones.vaciarLista();
            actualizarVista();
        });
    }

    private void actualizarCamposPorTipo() {
        String tipo = cmbTipo.getSelectedItem().toString();
        txtSala.setEnabled(tipo.equals("FuncionTradicional"));
        txtAsiento.setEnabled(tipo.equals("FuncionVIP"));
        txtAudio.setEnabled(tipo.equals("FuncionIMAX"));
    }

    private Proyeccion crearFuncionDesdeFormulario() {
        String titulo = txtTitulo.getText().trim();
        String director = txtDirector.getText().trim();
        String anioStr = txtAnio.getText().trim();

        if (titulo.isEmpty() || director.isEmpty() || anioStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Completa Título, Director y Año de Estreno.");
            return null;
        }

        int anio;
        try {
            anio = Integer.parseInt(anioStr);
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "El Año de Estreno debe ser un número entero.");
            return null;
        }

        String tipo = cmbTipo.getSelectedItem().toString();
        switch (tipo) {
            case "FuncionTradicional":
                String salaStr = txtSala.getText().trim();
                if (salaStr.isEmpty()) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Ingresa el N.º de Sala.");
                    return null;
                }
                try {
                    return new FuncionTradicional(titulo, director, anio, Integer.parseInt(salaStr));
                } catch (NumberFormatException ex) {
                    javax.swing.JOptionPane.showMessageDialog(this, "El N.º de Sala debe ser un número entero.");
                    return null;
                }

            case "FuncionVIP":
                String asientoStr = txtAsiento.getText().trim();
                if (asientoStr.isEmpty()) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Ingresa el N.º de Asiento VIP.");
                    return null;
                }
                try {
                    return new FuncionVIP(titulo, director, anio, Integer.parseInt(asientoStr));
                } catch (NumberFormatException ex) {
                    javax.swing.JOptionPane.showMessageDialog(this, "El N.º de Asiento VIP debe ser un número entero.");
                    return null;
                }

            case "FuncionIMAX":
                String audio = txtAudio.getText().trim();
                if (audio.isEmpty()) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Ingresa el sistema de Audio IMAX.");
                    return null;
                }
                return new FuncionIMAX(titulo, director, anio, audio);

            default:
                return null;
        }
    }

    private void actualizarVista() {
        if (listaFunciones.isEmpty()) {
            lblActual.setText("Función Actual Seleccionada: Ninguna");
            txtAreaLista.setText("La cartelera circular está vacía.");
        } else {
            lblActual.setText("Función Actual Seleccionada: " + listaFunciones.consultarActual().toString());
            txtAreaLista.setText(listaFunciones.mostrarTodos());
        }
    }

    private void limpiarCampos() {
        txtTitulo.setText("");
        txtDirector.setText("");
        txtAnio.setText("");
        txtPosicion.setText("");
        txtSala.setText("");
        txtAsiento.setText("");
        txtAudio.setText("");
    }
